import {
  mkdir,
  mkdtemp,
  readFile,
  rm,
  unlink,
  writeFile
} from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";

import {
  importMinimalPairsCorpus,
  validateGeneratedMinimalPairsCorpus,
  validateGeneratedTofuguPitchMinimalPairsCorpus
} from "@/features/pitch-accent/tooling";

describe("pitch accent minimal pairs importer", () => {
  it("normalizes upstream base64 audio into AAC files and a lightweight manifest", async () => {
    const tempDir = await mkdtemp(path.join(tmpdir(), "jcs-minimal-pairs-"));
    const sourceDir = path.join(tempDir, "source");
    const outDir = path.join(tempDir, "out");
    const audioBytes = buildAacFixtureBytes();

    try {
      await createFixtureSource(sourceDir, audioBytes);

      const result = await importMinimalPairsCorpus({
        allowNonVendorOutDir: true,
        importedAt: "2026-05-25T00:00:00.000Z",
        outDir,
        repositoryUrl: "https://github.com/Kuuuube/minimal-pairs",
        revision: "fixture",
        sourceDir
      });
      const manifest = JSON.parse(
        await readFile(path.join(outDir, "manifest.json"), "utf8")
      );

      expect(result).toMatchObject({
        audioFileCount: 2,
        pairCount: 1,
        variantCount: 2
      });
      expect(manifest.pairs[0].options[0]).toMatchObject({
        audioMime: "audio/aac",
        audioSrc: "/vendor/minimal-pairs/audio/0/0.aac",
        byteLength: audioBytes.length
      });
      await expect(
        readFile(path.join(outDir, ".minimal-pairs-vendor-generated"), "utf8")
      ).resolves.toContain("Generated by");
      expect(await validateGeneratedMinimalPairsCorpus({ outDir })).toEqual({
        errors: [],
        ok: true
      });

      await unlink(path.join(outDir, "audio", "0", "0.aac"));
      expect(
        (await validateGeneratedMinimalPairsCorpus({ outDir })).errors
      ).toContain("Missing audio file for 0:0.");
    } finally {
      await rm(tempDir, { recursive: true, force: true });
    }
  });

  it("refuses to replace non-standard output directories without an explicit allow flag", async () => {
    const tempDir = await mkdtemp(path.join(tmpdir(), "jcs-minimal-pairs-"));
    const sourceDir = path.join(tempDir, "source");
    const outDir = path.join(tempDir, "out");

    try {
      await createFixtureSource(sourceDir, buildAacFixtureBytes());

      await expect(
        importMinimalPairsCorpus({
          importedAt: "2026-05-25T00:00:00.000Z",
          outDir,
          repositoryUrl: "https://github.com/Kuuuube/minimal-pairs",
          revision: "fixture",
          sourceDir
        })
      ).rejects.toThrow("Refusing to replace non-standard");
    } finally {
      await rm(tempDir, { recursive: true, force: true });
    }
  });

  it("refuses to replace non-empty custom output directories even with the allow flag", async () => {
    const tempDir = await mkdtemp(path.join(tmpdir(), "jcs-minimal-pairs-"));
    const sourceDir = path.join(tempDir, "source");
    const outDir = path.join(tempDir, "out");

    try {
      await createFixtureSource(sourceDir, buildAacFixtureBytes());
      await mkdir(outDir, { recursive: true });
      await writeFile(path.join(outDir, "keep.txt"), "do not delete\n");

      await expect(
        importMinimalPairsCorpus({
          allowNonVendorOutDir: true,
          importedAt: "2026-05-25T00:00:00.000Z",
          outDir,
          repositoryUrl: "https://github.com/Kuuuube/minimal-pairs",
          revision: "fixture",
          sourceDir
        })
      ).rejects.toThrow("Refusing to replace non-empty custom");
      await expect(
        readFile(path.join(outDir, "keep.txt"), "utf8")
      ).resolves.toBe("do not delete\n");
    } finally {
      await rm(tempDir, { recursive: true, force: true });
    }
  });

  it("rejects manifest audio paths that escape the expected pair directory", async () => {
    const tempDir = await mkdtemp(path.join(tmpdir(), "jcs-minimal-pairs-"));
    const outDir = path.join(tempDir, "out");
    const audioBytes = buildAacFixtureBytes();

    try {
      await mkdir(outDir, { recursive: true });
      await writeFile(
        path.join(outDir, "LICENSE-GPL-3.0.txt"),
        "GNU GENERAL PUBLIC LICENSE\nVersion 3\n"
      );
      await writeFile(path.join(outDir, "NOTICE.md"), "Fixture notice.\n");
      await writeFile(
        path.join(outDir, "manifest.json"),
        `${JSON.stringify(buildEscapingManifest(audioBytes), null, 2)}\n`
      );

      const result = await validateGeneratedMinimalPairsCorpus({ outDir });

      expect(result.ok).toBe(false);
      expect(result.errors).toContain(
        "0:0 audio path escapes its pair directory."
      );
    } finally {
      await rm(tempDir, { recursive: true, force: true });
    }
  });

  it("rejects unsafe pair ids before resolving manifest audio paths", async () => {
    const tempDir = await mkdtemp(path.join(tmpdir(), "jcs-minimal-pairs-"));
    const outDir = path.join(tempDir, "out");

    try {
      await mkdir(outDir, { recursive: true });
      await writeFile(
        path.join(outDir, "LICENSE-GPL-3.0.txt"),
        "GNU GENERAL PUBLIC LICENSE\nVersion 3\n"
      );
      await writeFile(path.join(outDir, "NOTICE.md"), "Fixture notice.\n");
      await writeFile(
        path.join(outDir, "manifest.json"),
        `${JSON.stringify(buildUnsafePairManifest(), null, 2)}\n`
      );

      const result = await validateGeneratedMinimalPairsCorpus({ outDir });

      expect(result.ok).toBe(false);
      expect(result.errors).toContain("../escape has an unsafe pair id.");
      expect(result.errors).toContain("0:0 audio path has an unsafe pair id.");
    } finally {
      await rm(tempDir, { recursive: true, force: true });
    }
  });

  it("rejects Tofugu pitch corpora that are not binary or duplicate Kuuuube coverage", async () => {
    const tempDir = await mkdtemp(path.join(tmpdir(), "jcs-tofugu-validator-"));
    const outDir = path.join(tempDir, "tofugu");
    const kuuuubeManifestPath = path.join(tempDir, "kuuuube-manifest.json");
    const audioBytes = buildAacFixtureBytes();

    try {
      await mkdir(path.join(outDir, "audio", "tofugu_bad"), {
        recursive: true
      });
      await writeFile(path.join(outDir, "NOTICE.md"), "Fixture notice.\n");
      await writeFile(path.join(outDir, "audit.json"), "{}\n");
      await writeFile(
        path.join(outDir, "audio", "tofugu_bad", "0.aac"),
        audioBytes
      );
      await writeFile(
        path.join(outDir, "audio", "tofugu_bad", "1.aac"),
        audioBytes
      );
      await writeFile(
        path.join(outDir, "audio", "tofugu_bad", "2.aac"),
        audioBytes
      );
      await writeFile(
        path.join(outDir, "manifest.json"),
        `${JSON.stringify(buildNonBinaryTofuguManifest(audioBytes), null, 2)}\n`
      );
      await writeFile(
        kuuuubeManifestPath,
        JSON.stringify(buildKuuuubeCoverageManifest())
      );

      const result = await validateGeneratedTofuguPitchMinimalPairsCorpus({
        kuuuubeManifestPath,
        outDir
      });

      expect(result.ok).toBe(false);
      expect(result.errors).toEqual(
        expect.arrayContaining(["tofugu_bad must contain exactly two options."])
      );
    } finally {
      await rm(tempDir, { recursive: true, force: true });
    }
  });

  it("normalizes katakana Kuuuube coverage when validating Tofugu duplicates", async () => {
    const tempDir = await mkdtemp(path.join(tmpdir(), "jcs-tofugu-validator-"));
    const outDir = path.join(tempDir, "tofugu");
    const kuuuubeManifestPath = path.join(tempDir, "kuuuube-manifest.json");
    const audioBytes = buildAacFixtureBytes();

    try {
      await mkdir(path.join(outDir, "audio", "tofugu_duplicate"), {
        recursive: true
      });
      await writeFile(path.join(outDir, "NOTICE.md"), "Fixture notice.\n");
      await writeFile(path.join(outDir, "audit.json"), "{}\n");
      await writeFile(
        path.join(outDir, "audio", "tofugu_duplicate", "0.aac"),
        audioBytes
      );
      await writeFile(
        path.join(outDir, "audio", "tofugu_duplicate", "1.aac"),
        audioBytes
      );
      await writeFile(
        path.join(outDir, "manifest.json"),
        `${JSON.stringify(buildBinaryTofuguManifest(audioBytes), null, 2)}\n`
      );
      await writeFile(
        kuuuubeManifestPath,
        JSON.stringify(buildKuuuubeCoverageManifest("ハシ"))
      );

      const result = await validateGeneratedTofuguPitchMinimalPairsCorpus({
        kuuuubeManifestPath,
        outDir
      });

      expect(result.ok).toBe(false);
      expect(result.errors).toContain(
        "tofugu_duplicate duplicates a Kuuuube pitch contrast."
      );
    } finally {
      await rm(tempDir, { recursive: true, force: true });
    }
  });

  it("rejects absolute local paths in the public Tofugu audit artifact", async () => {
    const tempDir = await mkdtemp(path.join(tmpdir(), "jcs-tofugu-validator-"));
    const outDir = path.join(tempDir, "tofugu");
    const kuuuubeManifestPath = path.join(tempDir, "kuuuube-manifest.json");
    const audioBytes = buildAacFixtureBytes();

    try {
      await mkdir(path.join(outDir, "audio", "tofugu_duplicate"), {
        recursive: true
      });
      await writeFile(path.join(outDir, "NOTICE.md"), "Fixture notice.\n");
      await writeFile(
        path.join(outDir, "audit.json"),
        `${JSON.stringify(buildAbsolutePathAudit(), null, 2)}\n`
      );
      await writeFile(
        path.join(outDir, "audio", "tofugu_duplicate", "0.aac"),
        audioBytes
      );
      await writeFile(
        path.join(outDir, "audio", "tofugu_duplicate", "1.aac"),
        audioBytes
      );
      await writeFile(
        path.join(outDir, "manifest.json"),
        `${JSON.stringify(buildBinaryTofuguManifest(audioBytes), null, 2)}\n`
      );
      await writeFile(
        kuuuubeManifestPath,
        JSON.stringify(buildKuuuubeCoverageManifest("あめ"))
      );

      const result = await validateGeneratedTofuguPitchMinimalPairsCorpus({
        kuuuubeManifestPath,
        outDir
      });

      expect(result.ok).toBe(false);
      expect(result.errors).toContain(
        "audit.json source.jaydarSource must not be an absolute path."
      );
    } finally {
      await rm(tempDir, { recursive: true, force: true });
    }
  });
});

function buildAacFixtureBytes() {
  return Buffer.from([0xff, 0xf1, 0x50, 0x80, 0x00, 0x1f, 0xfc, 0x00]);
}

async function createFixtureSource(sourceDir: string, audioBytes: Buffer) {
  await mkdir(path.join(sourceDir, "data"), { recursive: true });
  await writeFile(
    path.join(sourceDir, "LICENSE"),
    "GNU GENERAL PUBLIC LICENSE\nVersion 3\n"
  );
  await writeFile(
    path.join(sourceDir, "data", "0"),
    JSON.stringify({
      kana: "とっか",
      pairs: [
        {
          accentedMora: 1,
          moraCount: 3,
          pitchAccent: 1,
          rawPronunciation: "トッカ",
          silencedMoras: [],
          soundData: audioBytes.toString("base64")
        },
        {
          accentedMora: 0,
          moraCount: 3,
          pitchAccent: 0,
          rawPronunciation: "トッカ",
          silencedMoras: [],
          soundData: audioBytes.toString("base64")
        }
      ]
    })
  );
}

