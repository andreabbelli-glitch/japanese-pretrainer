function buildUnsafePairManifest() {
  const manifest = buildEscapingManifest(buildAacFixtureBytes());
  manifest.pairs[0]!.id = "../escape";
  manifest.pairs[0]!.options[0]!.audioSrc =
    "/vendor/minimal-pairs/audio/../escape/0.aac";
  manifest.pairs[0]!.options[1]!.audioSrc =
    "/vendor/minimal-pairs/audio/../escape/1.aac";

  return manifest;
}

