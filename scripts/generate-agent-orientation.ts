export async function generateAgentOrientation(
  repositoryRoot: string
): Promise<string> {
  const skills = await discoverRepoScopedSkills(repositoryRoot);

  return buildAgentOrientationDocument({ skills });
}

export async function writeAgentOrientation(repositoryRoot: string) {
  const markdown = await generateAgentOrientation(repositoryRoot);
  await writeFile(
    path.join(repositoryRoot, agentOrientationPath),
    markdown,
    "utf8"
  );
}

export async function checkAgentOrientation(repositoryRoot: string) {
  const expected = await generateAgentOrientation(repositoryRoot);
  const targetPath = path.join(repositoryRoot, agentOrientationPath);
  let actual = "";

  try {
    actual = await readFile(targetPath, "utf8");
  } catch {
    return false;
  }

  return actual === expected;
}

function parseYamlLikeFrontmatter(source: string) {
  if (!source.startsWith("---\n")) {
    return {};
  }

  const endIndex = source.indexOf("\n---", 4);

  if (endIndex === -1) {
    return {};
  }

  const frontmatter = source.slice(4, endIndex).split("\n");
  const values: Record<string, string> = {};

  for (const line of frontmatter) {
    const separatorIndex = line.indexOf(":");

    if (separatorIndex === -1) {
      continue;
    }

    const key = line.slice(0, separatorIndex).trim();
    const value = line.slice(separatorIndex + 1).trim();

    if (key) {
      values[key] = value.replace(/^["']|["']$/g, "");
    }
  }

  return values;
}

function formatSkills(skills: RepoScopedSkill[]) {
  if (skills.length === 0) {
    return ["No repo-scoped skills found under `.agents/skills/`."];
  }

  return skills.map((skill) => {
    const suffix = skill.description ? `: ${skill.description}` : "";
    return `- ${formatCode(skill.name)} (${formatCode(skill.path)})${suffix}`;
  });
}

function formatCode(value: string) {
  return `\`${value}\``;
}

async function runCli() {
  const repositoryRoot = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    ".."
  );
  const checkOnly = process.argv.includes("--check");

  if (checkOnly) {
    const isCurrent = await checkAgentOrientation(repositoryRoot);

    if (!isCurrent) {
      console.error(
        `${agentOrientationPath} is out of date. Run ./scripts/with-node.sh pnpm docs:agent-orientation.`
      );
      process.exitCode = 1;
      return;
    }

    console.info(`${agentOrientationPath} is up to date.`);
    return;
  }

  await writeAgentOrientation(repositoryRoot);
  console.info(`Wrote ${agentOrientationPath}.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    await runCli();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
