export async function discoverRepoScopedSkills(
  repositoryRoot: string
): Promise<RepoScopedSkill[]> {
  const skillsRoot = path.join(repositoryRoot, ".agents", "skills");
  let entries: string[];

  try {
    entries = await readdir(skillsRoot);
  } catch {
    return [];
  }

  const skills = await Promise.all(
    entries.map(async (entry) => {
      const skillPath = path.join(skillsRoot, entry, "SKILL.md");

      try {
        const source = await readFile(skillPath, "utf8");
        const frontmatter = parseYamlLikeFrontmatter(source);

        return {
          name: frontmatter.name ?? entry,
          description: frontmatter.description ?? "",
          path: path.posix.join(".agents", "skills", entry, "SKILL.md")
        };
      } catch {
        return null;
      }
    })
  );

  return skills
    .filter((skill): skill is RepoScopedSkill => skill !== null)
    .sort((left, right) => left.name.localeCompare(right.name));
}

